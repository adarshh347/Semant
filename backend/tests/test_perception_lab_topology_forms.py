def fixture(name: str) -> Dict[str, Any]:
    return json.loads((FIXTURE_DIR / name).read_text(encoding="utf-8"))


def key(artifact: str, instance: str) -> str:
    return f"{artifact}#{instance}"


FOREST = "art_forms_forest"
PIERS = "art_forms_piers"
AMBIGUOUS = "art_forms_ambiguous"


# ── building relation sets by hand, for the cases geometry cannot produce ────


def relation(kind: str, source: str, target: str, *, artifact: str = FOREST,
             relation_id: Optional[str] = None, basis: str = "mask",
             status: str = "measured", directed: bool = True,
             measurements: Optional[Dict[str, float]] = None,
             source_artifact: Optional[str] = None,
             target_artifact: Optional[str] = None) -> Dict[str, Any]:
    """One relation, as JSON. Used where a real scene cannot make the case.

    A CONTAINMENT CYCLE IS THE MOTIVATING EXAMPLE, and it is worth saying why it must be
    hand-written. `nestedness_organ` will not report A inside B and B inside A off one raster —
    `MAX_SCALE_RATIO` forbids it. A cycle in the wild arrives the other way: two measurements taken
    at different revisions, on different bases, or in different runs, composed afterwards. Which is
    exactly what these producers do, and exactly why they have to survive it.
    """
    return {
        "relation_id": relation_id or f"rel_{kind}_{source}_{target}",
        "kind": kind,
        "source": {"artifact_id": source_artifact or artifact, "instance_id": source,
                   "scope": "session", "region_id": None, "geometry_rev": None},
        "target": {"artifact_id": target_artifact or artifact, "instance_id": target,
                   "scope": "session", "region_id": None, "geometry_rev": None},
        "directed": directed, "basis": basis, "epistemic_status": status,
        "measurements": measurements or {}, "stale": False,
    }


def relation_artifact(relations: Sequence[Dict[str, Any]], *, pairs_examined: int,
                      artifact_id: str = "art_hand_relations", basis: str = "mask",
                      status: str = "measured") -> Dict[str, Any]:
    """A contract-shaped `topology.pair_relation` artifact around hand-written relations.

    Built by replacing the payload of a generated control rather than typed out, so that a change
    to the artifact envelope shows up in one place instead of in every hand-made case.
    """
    doc = copy.deepcopy(fixture("relations.forest.json"))
    doc["identity"]["artifact_id"] = artifact_id
    doc["identity"]["identity_refs"] = []
    doc["measurement"]["payload"] = {"variant": "topology_relation_set",
                                     "pairs_examined": pairs_examined,
                                     "relations": list(relations), "bounded_to": None}
    doc["measurement"]["epistemic_basis"] = basis
    doc["measurement"]["epistemic_status"] = status
    return PerceptualArtifact.model_validate(doc).model_dump(mode="json")


def inverted(doc: Dict[str, Any]) -> Dict[str, Any]:
    """The same relation set, every nesting spelled from the other end.

    `contains(A→B)` and `nested_within(B→A)` are one measurement read from two sides. This swaps
    the spelling without touching the measurement, which is what lets the direction law be tested
    as an EQUIVALENCE rather than as two separate assertions that happen to agree.
    """
    out = copy.deepcopy(doc)
    flip = {"contains": "nested_within", "nested_within": "contains"}
    for rel in out["measurement"]["payload"]["relations"]:
        if rel["kind"] in flip:
            rel["kind"] = flip[rel["kind"]]
            rel["source"], rel["target"] = rel["target"], rel["source"]
    return out


def tree(*sets: Dict[str, Any], roster: Optional[Roster] = None) -> C.ContainmentReading:
    return C.produce_containment_tree(list(sets), roster=roster)


def parents(reading: C.ContainmentReading) -> Dict[str, Optional[str]]:
    return {n.node_id: n.parent_node_id for n in reading.payload.nodes}


