"""
PERCEPTUAL-FORMS-001D — what the structural Topology forms are allowed to say.

Organised by the CLAIMS these producers have to earn, not by the functions they happen to have.
The deliverable is not "four producers run"; it is that a person reading a tree, a graph, a
transition or a conditional set can believe what it says AND can see what it left out:

    direction      a nesting means the same thing in both spellings, and the tree is the same tree
    reduction      a redundant ancestor is ABSORBED by transitivity, never deleted
    disagreement   cycles and incomparable parents are reported, never broken or chosen between
    identity       a node is `artifact_id#instance_id`. A label never merges two of them, and a
                   revision never mints a third
    bounds         a declared member with no edges stays visible; an undeclared endpoint is refused
    revision       a transition cites four pinned references, and a threshold crossing is a change
                   in the RELATION and not in the object
    hypotheses     every conditional relation keeps its condition, no kind is ever averaged, and
                   no reading is dropped for being unlikely
    ceilings       box basis stays interpretive; a composition never outruns its weakest input
    isolation      no Extent call, no Depth call, no database, no post — proved on the import
                   closure rather than promised in a docstring

THE CONTROLS ARE SYNTHETIC AND COMMITTED, generated by
`scripts/perception_lab_topology_form_fixtures.py`: rectangles on a 40x60 raster whose structure is
known before the organ runs, each written twice — as the `extent_set` a topology operation consumes
and as the `topology_relation_set` the façade measured from it. The suite runs the generator's
`--check` by name, so a scene edited and not regenerated fails here rather than drifting quietly.

The mutation tests at the end are the other half. Each deletes one guard and asserts the deletion
turns a named test red — a law nothing fails on is a comment.
"""
