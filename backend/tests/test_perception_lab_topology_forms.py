def test_the_committed_controls_are_what_the_generator_builds():
    """`--check` by name, so a scene edited and not regenerated fails here.

    It is also a drift alarm on `topology.py`: the relation sets are what the real façade measured
    from the real scenes, so a change in how a relation is recorded reaches this suite as a diff a
    person reads rather than as a silent change in what the composition was tested against.
    """
    done = subprocess.run([sys.executable, str(FIXTURE_SCRIPT), "--check"],
                          capture_output=True, text=True, cwd=str(REPO_ROOT))
    assert done.returncode == 0, done.stderr


