def fixture(name: str) -> Dict[str, Any]:
    return json.loads((FIXTURE_DIR / name).read_text(encoding="utf-8"))


def context(**over: Any) -> T.LabContext:
    base = dict(session_id="labs_topology", run_id="run_1", step_id="step_1",
                source_image_digest=DIGEST, now=NOW)
    base.update(over)
    return T.LabContext(**base)


def pair(operation: str, artifact: Dict[str, Any], source: str, target: str,
         *, parameters: Optional[Dict[str, Any]] = None,
         extras: Sequence[Dict[str, Any]] = (), **over: Any) -> T.TopologyRequest:
    art_id = artifact["identity"]["artifact_id"]
    return T.TopologyRequest(
        operation=operation, context=context(),
        inputs=(T.TopologyInput(role="source", artifact_id=art_id, instance_id=source),
                T.TopologyInput(role="target", artifact_id=art_id, instance_id=target)),
        parameters=parameters or {}, extents=(artifact, *extras), **over)


def members(operation: str, artifact: Dict[str, Any], instance_ids: Sequence[str], *,
            role: str = "members", parameters: Optional[Dict[str, Any]] = None
            ) -> T.TopologyRequest:
    art_id = artifact["identity"]["artifact_id"]
    return T.TopologyRequest(
        operation=operation, context=context(),
        inputs=tuple(T.TopologyInput(role=role, artifact_id=art_id, instance_id=i)
                     for i in instance_ids),
        parameters=parameters or {}, extents=(artifact,))


def relations(result: T.TopologyResult) -> List[Any]:
    assert not result.refused, f"unexpected refusal: {result.refusal}"
    return list(result.artifact.measurement.payload.relations)


def only(result: T.TopologyResult) -> Any:
    found = relations(result)
    assert len(found) == 1, f"expected one relation, got {[r.kind.value for r in found]}"
    return found[0]


