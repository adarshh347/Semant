# ── the two bases keep different ceilings ────────────────────────────────────


def test_a_box_basis_containment_may_not_be_measured_however_confident():
    """THE WAVE2.5 RULING, in the laboratory. The finial-in-the-sky number, and its ceiling.

    The box reading of these two rectangles is a containment of 1.000 — the same shape of number
    that made `cseg_golden_finial_7` read as nested inside the sky. It is still reported, because
    a person comparing substrates needs to see what the coarse one said. It is `interpretive`.
    """
    boxed = only(T.run(pair("topology.containment", fixture("extent-set.box-only.json"),
                            "inst_inner", "inst_outer")))
    masked = only(T.run(pair("topology.containment", fixture("extent-set.containment.json"),
                             "inst_inner", "inst_outer")))
    assert boxed.basis is EpistemicBasis.BOX
    assert boxed.epistemic_status is EpistemicStatus.INTERPRETIVE
    assert boxed.measurements["containment"] == pytest.approx(1.0, abs=1e-6)
    assert masked.basis is EpistemicBasis.MASK
    assert masked.epistemic_status is EpistemicStatus.MEASURED
    assert masked.measurements["containment"] == pytest.approx(1.0, abs=1e-6)
    assert boxed.epistemic_status is not masked.epistemic_status, \
        "identical numbers, different kinds of knowing — that is the whole ruling"


