def supplied_instances(*artifacts: Dict[str, Any]) -> Dict[Tuple[str, str], Dict[str, Any]]:
    out: Dict[Tuple[str, str], Dict[str, Any]] = {}
    for artifact in artifacts:
        art_id = artifact["identity"]["artifact_id"]
        for inst in artifact["measurement"]["payload"]["instances"]:
            out[(art_id, inst["instance_id"])] = inst
    return out


def test_every_returned_endpoint_resolves_to_an_input_identity_and_revision():
    """THE IDENTITY TEST, over every operation that returns relations.

    A relation cites endpoints and never carries the mask it measured, so the citation is the only
    thing tying the number back to the picture. An endpoint that resolved to nothing — or to a
    region without saying which revision of it — would be a relation nobody could check or
    invalidate.
    """
    known = supplied_instances(fixture("extent-set.containment.json"),
                               fixture("extent-set.contact.json"),
                               fixture("extent-set.overlap.json"),
                               fixture("extent-set.disjoint.json"),
                               fixture("extent-set.scene.json"),
                               fixture("extent-set.canonical.json"))
    for operation, result in every_operation_once():
        if result.artifact.identity.artifact_kind is not ArtifactKind.TOPOLOGY_RELATION_SET:
            continue
        for relation in result.artifact.measurement.payload.relations:
            for endpoint in (relation.source, relation.target):
                key = (endpoint.artifact_id, endpoint.instance_id)
                assert key in known, f"{operation} cited an endpoint nobody supplied: {key}"
                supplied = known[key]
                assert endpoint.region_id == supplied["region_id"]
                assert endpoint.geometry_rev == supplied["geometry_rev"]
                if endpoint.scope is IdentityScope.CANONICAL:
                    assert endpoint.region_id and endpoint.geometry_rev is not None


