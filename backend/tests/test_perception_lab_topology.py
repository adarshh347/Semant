"""
PERCEPTUAL-ORGANS-002 Lane C — what the Topology façade is allowed to say, and what it must refuse.

The suite is organised by the CLAIMS the lane has to earn rather than by the functions it happens
to have, because the deliverable is not "seven operations run" — it is that a person can believe
what comes back:

    direction        `nested_within` and `contains` are one measurement read from two ends, and
                     swapping the endpoints swaps the word
    symmetry         `meets` reads the same both ways; the contact FRACTION does not, and the key
                     says whose perimeter it is of
    consistency      `disjoint` means one thing in every operation that can say it
    ceilings         a mask relation may be `measured`; a box relation may not, however confident
    absence          measured-and-nothing, refused, and never-run are three different records
    identity         every endpoint resolves back to an input, with its revision
    isolation        no Extent call, no Depth model, no database, no post

The mutation tests at the end are the other half. Each one breaks a specific rule and asserts the
break is caught — a law nothing fails on is a comment.

The controls are synthetic and committed: rectangles on a 40x60 raster, generated by
`scripts/perception_lab_topology_fixtures.py`, whose answers are known before the organ runs.
"""
