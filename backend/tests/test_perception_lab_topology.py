# ── adjacency: symmetric in kind, asymmetric in number ───────────────────────


def test_adjacency_finds_the_contact_and_its_locus():
    relation = only(T.run(pair("topology.adjacency", fixture("extent-set.contact.json"),
                               "inst_left", "inst_right")))
    assert relation.kind is RelationKind.MEETS
    assert relation.directed is False, "`meets` reads the same in both directions"
    assert relation.measurements["contact_pixels"] > 0
    assert relation.measurements["contact_fraction_of_source_perimeter"] >= \
        adjacency_organ.MIN_CONTACT
    assert relation.measurements["contact_locus_h"] > relation.measurements["contact_locus_w"], \
        "two rectangles sharing a column meet along a tall, narrow band"


def test_adjacency_is_symmetric_in_kind_and_asymmetric_in_number():
    """THE SYMMETRY TEST, and the half of it that is not symmetric.

    Whether two shapes meet does not depend on which is named first. HOW MUCH of a shape's own
    perimeter lies in the contact does — a small shape against a large one meets along most of
    itself and a sliver of the other — so the number is named for whose perimeter it measures.
    """
    contact = fixture("extent-set.contact.json")
    forward = only(T.run(pair("topology.adjacency", contact, "inst_left", "inst_right")))
    backward = only(T.run(pair("topology.adjacency", contact, "inst_right", "inst_left")))
    assert forward.kind is backward.kind is RelationKind.MEETS
    assert forward.measurements["contact_pixels"] == backward.measurements["contact_pixels"]

    # Same contact, different perimeters: a taller shape against a wider one.
    scene = fixture("extent-set.scene.json")
    a = only(T.run(pair("topology.adjacency", scene, "inst_outer", "inst_touching")))
    b = only(T.run(pair("topology.adjacency", scene, "inst_touching", "inst_outer")))
    assert a.kind is b.kind is RelationKind.MEETS
    assert a.measurements["source_perimeter_pixels"] != b.measurements["source_perimeter_pixels"]
    assert a.measurements["contact_fraction_of_source_perimeter"] != \
        b.measurements["contact_fraction_of_source_perimeter"]


def test_adjacency_reports_a_pair_that_does_not_touch_as_a_positive_disjoint():
    """The contract's "positive no-relation": measured, and they are apart, with the distance."""
    relation = only(T.run(pair("topology.adjacency", fixture("extent-set.disjoint.json"),
                               "inst_a", "inst_b")))
    assert relation.kind is RelationKind.DISJOINT
    assert relation.measurements["clearance_px"] > 0
    assert relation.measurements["contact_pixels"] == 0


def test_adjacency_will_not_call_an_enclosed_pair_disjoint():
    """One shape inside another neither meets its edge nor stands apart from it.

    The most confident wrong answer available here: their boundaries never touch, so a naive
    adjacency reports `disjoint` — of a pair where one shape is entirely inside the other. The
    honest record is a measured emptiness that names the operation which does answer it.
    """
    result = T.run(pair("topology.adjacency", fixture("extent-set.containment.json"),
                        "inst_inner", "inst_outer"))
    assert not result.refused
    assert result.outcome is RunOutcome.EMPTY
    assert result.artifact.measurement.payload.relations == []
    assert result.artifact.measurement.payload.pairs_examined == 1
    assert "overlap" in (result.artifact.interpretation.notes or "")


def test_adjacency_tolerance_is_recorded_and_changes_what_touching_means():
    scene = fixture("extent-set.disjoint.json")
    strict = only(T.run(pair("topology.adjacency", scene, "inst_a", "inst_b")))
    assert strict.measurements["contact_tolerance_px"] == 0.0
    generous = only(T.run(pair("topology.adjacency", scene, "inst_a", "inst_b",
                               parameters={"contact_tolerance_px": 3})))
    assert generous.measurements["contact_tolerance_px"] == 3.0
    assert generous.kind is RelationKind.DISJOINT, "three pixels does not close a forty-pixel gap"


