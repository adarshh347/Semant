// PERCEPTUAL-FORMS-001E — the fixtures, and where they come from.
//
// THE CONTRACT PAYLOADS ARE NOT RE-AUTHORED HERE. `formPayloads.json` beside this file is a
// bundle of the nineteen committed payloads at `contracts/fixtures/perception-lab/forms/`,
// keyed by form. It exists for one reason: the Vercel project uploads `frontend/` as its
// deployment source, so a browser bundle cannot import from the repo root — the same reason
// `frontend/src/contracts/perception-lab.v1.json` exists. It is regenerated, never edited:
//
//     UPDATE_FORM_FIXTURES=1 npx vitest run src/perceptionLab/forms/formFixtureDrift
//
// and `formFixtureDrift.test.js` fails when it and the canonical files disagree. A copy that
// nothing pins is a second contract with a head start.
//
// THE OTHER SCENARIOS ARE DERIVED, AND THE DERIVATION IS THE HONEST PART. The build asks for
// dense and empty states. Hand-authoring nineteen more payloads would produce nineteen more
// things that can drift from the grammar; instead each extra scenario is a small, visible,
// deterministic transformation of the committed one, so a change to the contract payload flows
// into every state automatically and no scenario can quietly stop being a valid record.
//
// FOUR STATES PER FORM, and each is a distinct finding the contract insists is not the others:
//
//   contract   the committed payload, exactly.
//   empty      the collection emptied, THE EXAMINATION COUNTER KEPT. "Looked and found nothing"
//              is a measurement. Dropping the counter with the contents would turn it into
//              "nothing here", which is the `empty_is_not_refused_is_not_unavailable` law's
//              whole subject.
//   dense      enough members to break a layout that was only ever tested with two.
//   withheld   fields only: the values replaced by a `data_ref` this page cannot read. The
//              renderer must refuse rather than draw a gradient from the statistics.
//
// NO RANDOMNESS ANYWHERE. Every dense scenario is generated by an index arithmetic so the same
// fixture produces the same picture in every run and in every screenshot.

import PAYLOADS from './formPayloads.json';

/** The nineteen committed payloads, keyed by form. Frozen: this is a mirror, not a workspace. */
export const FORM_PAYLOADS = Object.freeze(PAYLOADS);

